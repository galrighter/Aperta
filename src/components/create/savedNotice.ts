/**
 * מה נאמר במקום "העיצובים שלי" כשאין ברשימה כלום.
 *
 * הרשימה מצוירת מהאינדקס המקומי, והוא מתמלא משני מקורות: יצירה במכשיר הזה,
 * וסנכרון מהחשבון. במכשיר חדש (או אחרי ניקוי אחסון) המקור היחיד הוא השני —
 * ועד שהוא חוזר, ואם הוא נכשל, הרכיב פשוט לא מרנדר כלום. זה מה שהופך לחיצה על
 * "העיצובים שלי" בכותרת ל"לא קרה כלום": העמוד נטען, הרשימה ריקה, ואין שום
 * מילה שמסבירה אם היא נטענת, נכשלה, או שבאמת אין בה עיצובים.
 *
 * שלושת המצבים נבדלים, ורק אחד מהם הוא "אין מה להראות":
 * - `syncing` — המשיכה מהחשבון באוויר. נאמר רק למי שביקש את הרשימה במפורש
 *   (`?designs=1`); על מסך הפתיחה הרגיל שורה מהבהבת היא רעש.
 * - `failed`  — המשיכה נכשלה. נאמר תמיד: מי שיש לו עיצובים בחשבון ורואה מסך
 *   ריק צריך לדעת שזו תקלה ולא מחיקה.
 * - `null`    — אין חשבון (אין מאיפה למשוך), או שהמשיכה חזרה ובאמת אין עיצובים.
 */
export type SavedNotice = "syncing" | "failed" | null;

export function savedNotice(x: {
  /** כמה עיצובים כבר יש ברשימה. */
  items: number;
  /** יש חשבון מחובר — כלומר יש מקור שני לרשימה. */
  account: boolean;
  /** הסנכרון מהחשבון באוויר. */
  syncing: boolean;
  /** הסנכרון האחרון נכשל. */
  failed: boolean;
  /** נכנסו דרך "העיצובים שלי" בכותרת, ולא סתם למשפך. */
  requested: boolean;
}): SavedNotice {
  // יש מה להראות, או שאין חשבון שממנו אפשר למשוך — הרשימה מדברת בעד עצמה.
  if (x.items > 0 || !x.account) return null;
  if (x.failed) return "failed";
  if (x.syncing && x.requested) return "syncing";
  return null;
}
