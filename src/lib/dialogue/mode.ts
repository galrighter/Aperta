// dialogue mode — מזהה המסלול, המודל שלו, והתנאי שקובע אם שלב הטקסט רץ.
//
// **למה הקובץ הזה קיים בנפרד מ-`editStage.ts`.** מי שמחליט אם השלב רץ הוא
// נתיב היצירה, ומי שבודק את ההחלטה הזו הוא טסט אי־פגיעה שאסור לו לגעת ב-LLM.
// הפרדה של התנאי מהקריאה היא מה שמאפשר לבדוק אותו כלוגיקה טהורה — בדיוק
// כמו `isStory` ב-`lib/story/mode.ts`, שנבנה מאותו נימוק.
//
// המסלול כולו מסומן `dialogue mode`: ‏`grep -rn "dialogue mode" src/` מוצא כל
// נגיעה בקובץ קיים, ומחיקת הניסוי היא מחיקת `src/lib/dialogue/` ושחזור מה
// שהחיפוש הזה מחזיר.

/** מזהה המצב, כפי שהוא נוסע בבקשות. מחרוזת אחת, בקובץ אחד. */
export const DIALOGUE_MODE = "dialogue";

export type DialogueMode = typeof DIALOGUE_MODE;

/**
 * המודל והמאמץ של שלב הטקסט בעריכה — **המכהן** (החלטת גל, 18.8).
 *
 * זהו בדיוק מה שרץ ב-`lib/story/designStage.ts`, ולא במקרה: §5.4 ב-
 * `docs/DIALOGUE_PLAN.md` קובע שאין סיבה להחליף את המכהן בלי מדידה, ו-A0 היא
 * המדידה. יש לזה גם נימוק שאינו עצלנות — כששני השלבים רצים על אותו ספק, אותו
 * מודל ואותו מאמץ, ההשוואה בין המסלול הדו־שלבי למסלול של היום היא על
 * **הפרומפט** ולא על הספק. מועמד אחר שנכנס כאן היה מערבב את שני המשתנים.
 *
 * הרתמה (`lib/dialogue/lab.ts`) סוכנת־מודל בכוונה: היא מקבלת מודל ומאמץ
 * כפרמטרים, כך שהמועמדים של §5.4 נבדקים בלי לגעת בשורה הזו.
 */
export const DIALOGUE_EDIT = {
  model: "gpt-5.6-luna",
  effort: "medium",
} as const;

/** האם הבקשה הזו היא במסלול Dialogue. */
export const isDialogue = (mode: string | null | undefined): boolean => mode === DIALOGUE_MODE;

/**
 * מה נכנס לשלב הטקסט — התנאי, לבדו.
 *
 * **זה הלב של "מסלול מקביל", ולכן הוא פונקציה ולא `if` בתוך הנתיב.** מה
 * ש-`/design` בלי `?dialogue=1` עושה חייב להיות ניתן להוכחה, לא להסתמכות על
 * קריאה חוזרת של 900 שורות נתיב. הפונקציה הזו היא כל ההבדל, והטסט שלה הוא
 * הראיה (`__tests__/dialogueUntouched.test.ts`).
 *
 * ארבעה תנאים, וכל אחד מהם שולל בפני עצמו:
 *
 *  1. **`mode === "dialogue"`** — בלי הדגל אין מסלול. זו השורה שמגינה על כל
 *     לקוחה שאינה בניסוי.
 *  2. **יש `currentSvg`** — זו בקשת שינוי ולא יצירה מאפס. יצירה במסלול הזה
 *     היא שלב B (שיחת החידוד) ואינה קיימת עדיין; עד אז יצירה ב-dialogue
 *     עוברת בדיוק במה שהמסלול הרגיל עובר בו.
 *  3. **אין `promptOverride`** — הבק־אופיס שכתב פרומפט ביד מבקש לשלוח אותו
 *     כמו שהוא. שלב טקסט שהיה רץ מעליו היה דורס בדיוק את מה שנבדק. אותו
 *     נימוק, מילה במילה, כמו ב-`storyCreate` בנתיב היצירה.
 *  4. **יש בקשה** — מחרוזת ריקה אינה בקשת שינוי, ואין מה לתרגם.
 *
 * הכיתוב (`text`) **אינו** שולל כאן, בניגוד ליצירה: בעריכה הכיתוב כבר יושב
 * בתוך העיצוב שנמסר כתמונת בסיס, ותמונת ייחוס שנייה ממילא לא נשלחת (ראה
 * `imageDropped` בנתיב היצירה). כלומר אין מה להתנגש איתו.
 */
export function runsEditStage(req: {
  mode?: string | null;
  currentSvg?: string | null;
  promptOverride?: string | null;
  userPrompt?: string | null;
}): boolean {
  return (
    isDialogue(req.mode)
    && Boolean(req.currentSvg)
    && !req.promptOverride?.trim()
    && Boolean(req.userPrompt?.trim())
  );
}
