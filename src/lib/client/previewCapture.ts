"use client";

/**
 * צילום ההדמיה התלת־ממדית שעל המסך, לשימוש כתמונת השיתוף.
 *
 * **למה רישום גלובלי ולא ref.** מי שמצלם הוא כפתור השיתוף, והוא לא שכן של
 * הקנבס באף אחד משני המקומות שבהם הוא מופיע: במסך התוצאה הוא בשורת הכותרת
 * ובסטודיו הוא ב-header, בעוד שהקנבס יושב עמוק בעץ אחר. להעביר ref בין
 * השניים היה אומר לחווט אותו דרך כל מסך התוצאה ודרך ה-store של הסטודיו, בשביל
 * פעולה שקורית פעם בלחיצה.
 *
 * **קנבס אחד בכל רגע.** אין מצב שבו שתי הדמיות מוצגות יחד, ולכן הרישום הוא
 * ערך יחיד ולא רשימה. רכיב שנפרק מנקה רק אם הוא עדיין הרשום — אחרת החלפת
 * טאב מהירה הייתה מוחקת את הרישום של מי שנכנס אחריו.
 */

type Capture = () => string | null;

let current: Capture | null = null;

export function registerPreviewCapture(fn: Capture): () => void {
  current = fn;
  return () => {
    if (current === fn) current = null;
  };
}

/**
 * ה-data URL של ההדמיה, או null כשאין קנבס מוצג (הסטודיו בטאב הפריסה,
 * דפדפן בלי WebGL). null אינו שגיאה — השיתוף פשוט נוצר בלי צילום.
 */
export function capturePreview(): string | null {
  try {
    return current?.() ?? null;
  } catch {
    return null;
  }
}
