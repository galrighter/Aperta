/**
 * כתובת למשלוח — בדיקות שאינן "לא ריק", לדפדפן ולשרת.
 *
 * ההבדל בין שדה ריק לשדה שגוי הוא שהראשון נראה. `.` בשדה "שם מלא" ו-`61` בשדה
 * "מיקוד" עוברים כל בדיקת אורך, ומתגלים רק על תווית משלוח.
 *
 * מה שנבדק כאן נשאר **סלחני כלפי מה שאינו ישראלי**: מיקוד בריטי הוא אותיות
 * וספרות, ושם יכול להיות בכל שפה. מה שנפסל הוא מה שאינו יכול להיות התשובה —
 * לא מה שאינו התשובה הצפויה.
 */

/** לפחות אות אחת, בכל אלפבית. שם שכולו ספרות או סימנים אינו שם. */
const HAS_LETTER = /\p{L}/u;

/** שם מלא: שני תווים לפחות, ובתוכם אות. */
export function nameValid(raw: string): boolean {
  const v = raw.trim();
  return v.length >= 2 && HAS_LETTER.test(v);
}

/** רחוב/עיר: שני תווים לפחות, ובתוכם אות. `14` אינו רחוב. */
export function addressLineValid(raw: string): boolean {
  const v = raw.trim();
  return v.length >= 2 && HAS_LETTER.test(v);
}

/**
 * מיקוד. שדה רשות — ריק הוא תקין.
 *
 * מיקוד ישראלי הוא **שבע ספרות** מאז 2013. הכלל כאן תופס את הטעות הנפוצה
 * (חמש ספרות, המיקוד הישן) בלי לפסול כתובת בחו"ל: מחרוזת שכולה ספרות נמדדת
 * מול 7, וכל דבר אחר — `SW1A 1AA` — עובר על אורך סביר בלבד.
 */
export function zipValid(raw: string): boolean {
  const v = raw.trim();
  if (!v) return true;
  if (/^\d+$/.test(v)) return v.length === 7;
  return v.length >= 3 && v.length <= 12;
}
