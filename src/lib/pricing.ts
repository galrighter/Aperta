import { type ProductType } from "./fabrication.config";

// תמחור (handoff §7) — מקום אחד, שני צדדים.
//
// עד עכשיו החישוב ישב ב-`src/components/create/model.ts`, כלומר בדפדפן בלבד,
// והשרת קיבל את `סה"כ` כמחרוזת בתוך גוף ההודעה. משמעות הדבר ששני דברים
// שנשמעים תיאורטיים היו נכונים בפועל: מה שנרשם כמחיר ההזמנה הוא מה שהדפדפן
// אמר (וכל מה שהדפדפן שולח אפשר לזייף), ושינוי מחירון היה משנה את המסך אבל לא
// את מה שנשמר בהזמנות קודמות. כאן החישוב טהור וחסר-מצב, המשפך והשרת קוראים
// לאותה פונקציה, וההזמנה נשמרת עם הפירוט שהשרת חישב.
//
// **כל מספר כאן כולל מע"מ** (החלטת גל, 29.7). זה לא ניסוח אלא מבנה: קודם
// המחירים היו נטו ו-17% נוספו מעליהם, ולכן "מחיר הצמיד" היה מספר שאיש לא רואה.
// עכשיו מה שכתוב הוא מה שמשלמים, והמע"מ נגזר **מתוך** הסכום (18/118) כשורת
// מידע — כפי שגם מחויב מול צרכן. הרווח הזה נבלע בכוונה: המחירים לא הועלו כדי
// לפצות על המעבר ל-18%.

export type Density = "low" | "medium" | "high";

export interface Price {
  /** צמיד/טבעת, כולל אריזה — לפני משלוח. כולל מע"מ. */
  base: number;
  shipping: number;
  /** מה שמשלמים. */
  total: number;
  /** המע"מ **הכלול** ב-total. שורת מידע, לא תוספת. */
  vat: number;

  /* ===== רכיבים היסטוריים =====
     עד למחיר הקבוע (החלטת גל) המחיר נשא שתי תוספות משתנות: `widthAdd` לפי
     הרוחב ו-`complexity` לפי הצפיפות. הן **אינן מחושבות יותר** — אבל הן שמורות
     בעמודת `price` (jsonb) של כל הזמנה שנשלחה לפניהן, וזו רשומה היסטורית של מה
     שנגבה בפועל. לכן הן נשארות בטיפוס כאופציונליות: הבק־אופיס וסיכום ההזמנה
     ממשיכים להציג אותן בהזמנות ישנות, ולא מציגים אותן בחדשות. */
  /** @deprecated תוספת רוחב — בהזמנות שנשלחו לפני המחיר הקבוע בלבד. */
  widthAdd?: number;
  /** @deprecated תוספת מורכבות — בהזמנות שנשלחו לפני המחיר הקבוע בלבד. */
  complexity?: number;

  /* ===== קוד הפניה (0026) ===== */
  /** הקוד שתומחר בו, כפי שנקלט. חסר בהזמנה רגילה. */
  referralCode?: string;
  /**
   * מחיר המחירון לאותו פריט, כשקוד הפניה הזיז אותו.
   *
   * נשמר כדי שאפשר יהיה לענות בדיעבד "כמה ויתרנו על הקוד הזה" בלי לשחזר את
   * המחירון שהיה באותו יום — `BASE` הוא קבוע בקוד, והוא ישתנה. **אינו מוצג
   * ללקוחה בשום מסך**: מחיר מחוק לצד המחיר שמשלמים הוא בדיוק מה שהקוד נועד
   * למנוע. שורת בק־אופיס וחשבונאות בלבד.
   */
  listBase?: number;
}

/**
 * איך קוד הפניה קובע את מחיר הפריט (migration 0026).
 *
 * היום נדרש `fixed_price` בלבד; `percent_off` קיים כי הפניה מחנות עשויה
 * לזכות באחוז, וההחלטה טרם התקבלה. שני הכללים חלים על **הפריט בלבד** —
 * המשלוח הוא עלות אמיתית וממשיך להיגבות ככתבו.
 */
export type ReferralRule =
  | { kind: "fixed_price"; basePrices: Record<ProductType, number> }
  | { kind: "percent_off"; percentOff: number };

/**
 * מחיר הפריט לפי הקוד. פונקציה טהורה, ולכן היא זו שנבדקת — ולא המסלול.
 *
 * ‏`Math.max(0, …)` אינו הגנה תיאורטית: אחוז שנשמר שגוי, או מחיר שלילי
 * שהוקלד בבק־אופיס, היו הופכים את `total` לסכום נמוך מהמשלוח — כלומר הזמנה
 * שגובה פחות מעלות המשלוח שכבר שולמה.
 */
export function referralBase(rule: ReferralRule, productType: ProductType): number {
  const list = BASE[productType];
  const raw =
    rule.kind === "fixed_price"
      ? rule.basePrices[productType]
      : Math.round((list * (100 - rule.percentOff)) / 100);
  // מחיר שלא נמסר למוצר הזה נופל למחירון ולא ל-NaN. אמור להיחסם כבר
  // ב-check constraint של 0026, וכפילות כאן זולה מהזמנה עם `total: NaN`.
  if (!Number.isFinite(raw)) return list;
  return Math.max(0, Math.round(raw));
}

/** מחיר פריט סטנדרטי לפני משלוח, כולל מע"מ ואריזה. */
const BASE: Record<ProductType, number> = { bracelet: 399, ring: 299 };
export const SHIPPING = 35;

/** מע"מ בישראל מ-2025. הסכומים כוללים אותו — הוא נגזר מהם ולא מתווסף להם. */
export const TAX_RATE = 0.18;

/** המע"מ הכלול בסכום. */
export const vatIn = (grossTotal: number): number =>
  Math.round((grossTotal * TAX_RATE) / (1 + TAX_RATE));

/**
 * **מחיר קבוע למוצר** (החלטת גל) — הקלט היחיד הוא מה מייצרים.
 *
 * מה שהיה כאן ואיננו: שתי תוספות משתנות. `widthAdd` הוסיפה ₪5 לכל מ"מ בצמיד
 * ו-₪14 בטבעת מעל רוחב ברירת המחדל, ו-`complexity` הזיזה ‎−45/0/+65 לפי
 * הצפיפות שנבחרה. שתיהן הוסרו משני המסלולים גם יחד.
 *
 * **למה.** המחיר שהאתר מבטיח בכרטיס המוצר הוא "₪399 כולל מע"מ", והוא היה נכון
 * רק לפריט בברירת המחדל; כל בחירה אחרת גילתה מספר אחר בסוף המסע. במסלול הסיפור
 * זה הפך לבלתי אפשרי ממש — שם הרוחב אינו נבחר אלא נגזר מהעיצוב שחזר, כך
 * שהתוספת הייתה נגבית על משהו שהלקוחה מעולם לא ביקשה ולא יכלה לצפות.
 *
 * מספר אחד למוצר הוא גם מה שמאפשר להבטיח אותו לפני היצירה, בכל מסלול.
 *
 * הפקדים עצמם לא הוסרו: הרוחב והמאפיינים במסלול הרגיל נשארים בדיוק כפי שהיו,
 * ומעצבים את הפריט. הם פשוט אינם מזיזים את המחיר.
 */
export interface PriceInput {
  productType: ProductType;
  /**
   * קוד הפניה שנקלט ואומת (0026). כשהוא כאן, מחיר הפריט נקבע ממנו במקום
   * מ-`BASE` — והפונקציה נשארת טהורה: מי שפותר את הקוד מול המסד הוא המסלול
   * ב-`/api/orders`, וכאן מגיע כבר הכלל עצמו.
   *
   * **המחיר לעולם אינו נקבע בדפדפן.** הדפדפן קורא לפונקציה הזאת כדי להציג,
   * אבל מה שנשמר הוא מה שהשרת חישב מהקוד ששלף מהמסד בעצמו. ראו את בדיקת
   * ההתאמה ב-`/api/orders`.
   */
  referral?: { code: string; rule: ReferralRule; pickupOnly?: boolean } | null;
}

export function priceFor({ productType, referral }: PriceInput): Price {
  const list = BASE[productType];
  const base = referral ? referralBase(referral.rule, productType) : list;
  // **איסוף עצמי — אין משלוח לגבות.** ‏`pickupOnly` יושב לצד `rule` ולא בתוכו
  // כי הוא ציר אחר: קוד חנות יכול לתת מחיר מיוחד ועדיין להישלח.
  const shipping = referral?.pickupOnly ? 0 : SHIPPING;
  const total = base + shipping;
  const price: Price = { base, shipping, total, vat: vatIn(total) };
  // שתי השורות נכתבות רק כשהיה קוד: הזמנה רגילה נשמרת בדיוק כפי שנשמרה עד
  // היום, ו-`priceLineParts` ממשיך להדפיס אותה בלי שינוי.
  if (referral) {
    price.referralCode = referral.code;
    price.listBase = list;
  }
  return price;
}
