/**
 * טלפון — נרמול ובדיקת תקינות, במקום אחד לדפדפן ולשרת.
 *
 * הטלפון הוא הדרך שבה גל מתקשר ללקוחה כדי לאשר שרטוט לפני ייצור. מספר שגוי
 * אינו שדה ריק שרואים מיד — הוא נראה מלא, עובר את כל המסך, ומתגלה רק כשאי
 * אפשר להשיג אותה. לכן הבדיקה נאכפת **בשני הצדדים**: בדפדפן כדי שהטעות תתוקן
 * בזמן ההקלדה, ובשרת כי מה שהדפדפן שולח אינו מה שהוא מציג.
 *
 * שלוש החלטות:
 *
 * · **תווי עיצוב אינם טעות.** רווחים, מקפים, נקודות וסוגריים הם הדרך שבה
 *   אנשים מקלידים טלפון (`050-123 4567`, `(03) 5551234`). הם מוסרים לפני
 *   הבדיקה במקום להיפסל — פסילה עליהם היא פסילה של הקלדה נכונה.
 *
 * · **קידומת ישראל מתורגמת ולא נשמרת פעמיים.** `+972-50-1234567` ו-`00972…`
 *   הם אותו מספר כמו `050-1234567`, וכך הם גם נשמרים; אחרת אותה לקוחה מופיעה
 *   בבק־אופיס כשתי רשומות שאי אפשר להצליב.
 *
 * · **מספר בין־לאומי מפורש מתקבל.** האתר ישראלי, אבל לקוחה שמזמינה מחו"ל היא
 *   הזמנה אמיתית. מה שנפסל הוא מה שאינו מספר טלפון — לא מה שאינו ישראלי.
 */

/** מה שמוסר לפני הבדיקה: כך אנשים מקלידים, וזו אינה טעות. */
const NOISE = /[\s\-().‐-―]/g;

/** נייד: 050–059. */
const IL_MOBILE = /^05\d{8}$/;
/** קווי־אינטרנט וספקים וירטואליים: 072–079. */
const IL_VIRTUAL = /^07[2-9]\d{7}$/;
/** קווי: 02, 03, 04, 08, 09. */
const IL_LANDLINE = /^0[23489]\d{7}$/;
/** בין־לאומי מפורש — קידומת מדינה ואחריה מספר באורך סביר. */
const INTERNATIONAL = /^\+[1-9]\d{7,14}$/;

/**
 * הצורה השמורה של מה שהוקלד: בלי תווי עיצוב, וקידומת ישראל כ-0 מוביל.
 *
 * מחזירה את המחרוזת המנוקה גם כשהיא אינה מספר תקין — התשובה על "האם זה תקין"
 * היא של `isValidPhone`, ולא של פונקציה שמחזירה מחרוזת ריקה ומאבדת את מה
 * שהמשתמשת הקלידה.
 */
export function normalizePhone(raw: string): string {
  let s = raw.trim().replace(NOISE, "");
  if (!s) return "";
  if (s.startsWith("00")) s = `+${s.slice(2)}`;
  if (s.startsWith("+972")) {
    // `+972 50` ו-`+972 050` שניהם נפוצים; שניהם אותו מספר.
    s = `0${s.slice(4).replace(/^0+/, "")}`;
  }
  return s;
}

/** האם מה שהוקלד הוא מספר טלפון שאפשר להתקשר אליו. */
export function isValidPhone(raw: string): boolean {
  const s = normalizePhone(raw);
  if (!s) return false;
  return (
    IL_MOBILE.test(s) || IL_VIRTUAL.test(s) || IL_LANDLINE.test(s) || INTERNATIONAL.test(s)
  );
}

/**
 * הצורה שמוצגת ונשמרת: `050-1234567`, `03-5551234`, ובין־לאומי כפי שהוא.
 *
 * מספר לא תקין מוחזר כמות שהוא — עיצוב של קלט שגוי גורם לו להיראות נכון.
 */
export function formatPhone(raw: string): string {
  const s = normalizePhone(raw);
  if (!isValidPhone(s)) return raw.trim();
  if (IL_MOBILE.test(s) || IL_VIRTUAL.test(s)) return `${s.slice(0, 3)}-${s.slice(3)}`;
  if (IL_LANDLINE.test(s)) return `${s.slice(0, 2)}-${s.slice(2)}`;
  return s;
}
