/**
 * הכתובת של תמונת הרצה — כתובת אחת, מגודרת, לכל מי שמציג אותה.
 *
 * התמונות יושבות ב-bucket פרטי, והדרך היחידה להגיע אליהן היא כתובת חתומה.
 * היו לזה שני מימושים: היומן מחזיר קישור למסלול (`/api/debug/log/<id>/image/
 * <name>`) שחותם בעצמו מאחורי שער האדמין, ואילו `/api/generate` חתם בעצמו
 * והחזיר את הכתובת החתומה כמו שהיא לדפדפן.
 *
 * השני הוא זה שנפרם:
 * - הכתובת החתומה נוסעת ללקוח **וגם נשמרת בשורת ה-job**, כי היא חלק מתשובת
 *   היצירה. סוד שנשמר בטבלה הוא סוד שאפשר לקרוא ממנה.
 * - היא פגה אחרי שעה. הצופה בתשובה השמורה מקבל 400 מ-Supabase, שנראה בדיוק
 *   כמו תמונה חסרה.
 * - היא מצביעה על דומיין אחר, ולכן היא כפופה ל-`img-src` — וזה בדיוק מה
 *   ששבר את הבק־אופיס ב-16.8.
 *
 * המסלול פותר את שלושתם: הכתובת יציבה, היא לא נושאת סוד, והחתימה נעשית בבקשה
 * לתמונה עצמה — מול השער, ועם התקציב שלה. מי שמציג את התמונות (יומן היצירות,
 * הסטודיו, מעבדת ההרצה) יושב ממילא מאחורי שער האדמין.
 */

/** התמונות שהרצה שומרת. `render` היא ההדמיה; השאר הם שלבי הצינור. */
export const RUN_IMAGE_NAMES = [
  "render",
  "input",
  "reference",
  "conditioned",
  "overlay",
  "difference",
  "rendered",
] as const;

export type RunImageName = (typeof RUN_IMAGE_NAMES)[number];

export const isRunImageName = (name: string): name is RunImageName =>
  (RUN_IMAGE_NAMES as readonly string[]).includes(name);

/**
 * הכתובת המגודרת לתמונה אחת.
 *
 * `runId` הוא **ההרצה שהתמונה נשמרה עליה**, ולא בהכרח ההרצה שהתשובה מדווחת
 * עליה: כשניסיון שני הוא זה שהצליח, ההדמיה יושבת על שורת הניסיון השני
 * (`generationId`). מסלול התמונה קורא `render_path` מהשורה שביקשו, ושורה
 * אחרת פירושה 404.
 */
export const runImageUrl = (runId: string, name: RunImageName): string =>
  `/api/debug/log/${runId}/image/${name}`;
