import { FAB } from "@/lib/fabrication.config";
import { LANDSCAPE, aspect, type Canvas } from "./canvas";

// כמה פריטים לבקש בתמונה אחת.
//
// מודל התמונה לא מצייר את היחס שמבקשים ממנו — הוא נמשך ליחס "נוח" משלו. נמדד על
// 45 הרצות (26.7): בקשה ל-4.0 חזרה כ-4.8, בקשה ל-6.4 חזרה כ-5.9, ובקשה ל-16
// חזרה כ-8.3. ניסוח לא מזיז את זה.
//
// מה שכן מזיז אותו הוא צורת הקנבס. כשמבקשים ממנו לחלק את התמונה ל-N שורות, כל
// שורה היא מסגרת צרה, והנטייה שלו למלא את השטח שלו עובדת לטובתנו:
//   שורה אחת → ~6.5 · שתיים → ~7.8 · ארבע → ~10.5 · שש → ~12.8
// מכאן מספר השורות: זה שהיחס הטבעי שלו הקרוב ביותר למה שהוזמן.
//
// **אין יעד מועמדים, ואין קריאה שנייה** (החלטת גל, 30.7). קודם מספר השורות נגזר
// מהיחס, ואז קריאה שנייה השלימה אותו ל"כמה חלופות המסך מציג" (ארבע) — כך שצמיד
// סטנדרטי (יחס 8.9 → שלוש שורות) שילם כפול כדי לקבל שישה מועמדים במקום שלושה,
// ושני האחרונים לא נתבקשו מעולם. עכשיו: השורות נגזרות מהיחס בלבד, הקריאה אחת,
// ומספר החלופות הוא מה שיצא — פריט רחב מחזיר אחת, פריט צר מחזיר הרבה.
//
// **מה שהשתנה מאז: עמודות.** הכלל למעלה נגזר מהיחס בלבד, ולכן פריט קצר — טבעת —
// קיבל שורה אחת, כלומר חלופה אחת, וגם משפט LAYOUT לא נכלל בפרומפט בכלל. השורות
// לא היו הידית האמיתית: היא צורת התא, ו-2x2 שומר עליה בדיוק כמו 1x1. מה שמגביל
// היה תקציב הפיקסלים, והוא נמדד מול אורך הפריט — כלומר דווקא בטבעת יש עודף
// (55 מ"מ על חצי קנבס > 160 מ"מ על קנבס שלם). מכאן: כשהשורות לבדן מחזירות פחות
// חלופות ממה שהמסך מציג והפריט קצר מספיק, נוספת עמודה. עדיין קריאה אחת, אותו
// יחס, אותה איכות — רק חלוקה אחרת של אותה תמונה.
//
// זה נכון **גם לעריכה**. קודם עריכה קיבלה שורה אחת בארבע קריאות, בנימוק שמול
// תמונת רפרנס היחס מגיע מהרפרנס ולכן צורת הקנבס כבר לא ידית. הנימוק לא נמדד
// מעולם — 45 ההרצות היו טקסט→תמונה — והרפרנס והשורות דוחפים לאותו יחס, לא זה
// נגד זה. אם יתברר אחרת, זה יימדד: היומן מדווח "אורך נגזר" לכל הרצה.
//
// כאן נשאר רק התכנון. החיתוך עצמו עבר לקופסה (vectorizer/app/core/panels.py):
// פענוח וכתיבה של PNG ב-JS נכתבו מלכתחילה רק כי sharp לא רץ על Workers.

/**
 * היחס שהמודל מצייר בפועל — מהמדידות שלמעלה.
 *
 * מה שמזיז אותו הוא צורת התא שהפריט יושב בו, לא מספר השורות כשלעצמו: ארבע
 * המדידות נופלות על ישר יחיד כשמסתכלים על יחס הצדדים של התא (1.5·שורות/עמודות
 * בקנבס 1536x1024) — 1.5→6.55, 3→7.8, 6→10.3, 9→12.8. מכאן שהצורה נשמרת כשמכפילים
 * שורות ועמודות יחד: 2x2 מצייר את אותו יחס כמו 1x1, בארבעה פריטים במקום אחד.
 * זו כל הידית שהעמודות נותנות (ראה planRender).
 */
const RATIO_INTERCEPT = 5.3;
/** מה ששורה אחת שווה ביחס המצויר בקנבס לרוחב. הכללה: `SLOPE · יחס-הקנבס/1.5`,
 *  כך שהמספרים לרוחב נשארים בדיוק מה שהיו (1.5/1.5 = 1). */
const RATIO_PER_ROW_LANDSCAPE = 1.25;
const ratioPerRow = (c: Canvas) => RATIO_PER_ROW_LANDSCAPE * (aspect(c) / aspect(LANDSCAPE));

export const NATURAL_RATIO = (rows: number, cols = 1, canvas: Canvas = LANDSCAPE) =>
  RATIO_INTERCEPT + (ratioPerRow(canvas) * rows) / cols;

/** ההיפוך: כמה שורות **לכל עמודה** צריך כדי שהיחס המצויר יהיה זה שהוזמן. */
const rowsPerColumn = (ratio: number, canvas: Canvas) =>
  Math.round((ratio - RATIO_INTERCEPT) / ratioPerRow(canvas));

/**
 * צפיפות הייחוס: מה שצמיד באורך ברירת המחדל מקבל היום, בעמודה אחת, לרוחב.
 * 8.64 px/mm. כל שאר החסמים נמדדים מולה, ולכן היא נשארת קבועה גם כשהקנבס משתנה
 * — קנבס אחר לא אמור להזיז את הרף, רק לשנות מי עומד בו.
 */
const REFERENCE_PX_PER_MM =
  (LANDSCAPE.widthPx * 0.9) / FAB.products.bracelet.defaultLengthMm;

/**
 * כמה מגובה השורה הפריט באמת תופס. נמדד: בשלוש שורות מסגרת השורה היא 4.5:1
 * והפריט המצויר 9:1 — כלומר הוא ממלא את הרוחב ומשאיר כמחצית הגובה לבן, בדיוק
 * כפי שהפרומפט מבקש ("leave plenty of plain white above and below it").
 */
const ROW_FILL = 0.5;

/** כמה מרוחב העמודה הפריט תופס. הפרומפט מבקש "כמעט את מלוא הרוחב עם שוליים
 *  לבנים דקים בשני הקצוות" — בניגוד לגובה, שם הוא מבקש במפורש להשאיר לבן. */
const COL_FILL = 0.9;

/**
 * כמה חלופות המסך מציג. אין כאן יעד שמצדיק קריאה שנייה — ההחלטה מ-30.7 עומדת
 * ועלות היא עדיין קריאה אחת. זה יעד לחלוקת אותה תמונה: כשהפריט קצר מספיק,
 * עמודה נוספת קונה חלופות בלי לשלם עליהן בפרופורציה, באיכות או בכסף.
 */
const TARGET_CANDIDATES = 4;

/**
 * כמה חלופות מוצגות ללקוחה לכל היותר.
 *
 * **זו תקרת תצוגה, ולא תקרת ייצור** (11.8). עד כאן היא ישבה באותו `min` עם
 * תקציב הפיקסלים ועם מה שהיחס דורש, ולכן היא הגבילה בשקט גם את **צורת התא** —
 * כלומר את היחס שהמודל מצייר. השורות משרתות שני תפקידים (היחס, ומספר
 * הפריטים), ומספר שנכתב עבור השני חתך את הראשון: ב-AP-0096 היחס דרש 43 שורות,
 * תקציב הפיקסלים הרשה 25, והתכנון לקח 6 — כלומר תא של 8.6:1 להזמנה של 29:1,
 * ומתיחה של ×4.2 שמעכה את הדוגמה עד שנפסלה.
 *
 * מכאן היא חלה רק במקום שבו היא באמת שייכת: כמה מהפסים שנחתכו מוצעים לבחירה
 * (`offered`), וכמה עמודות מותר להוסיף — כי עמודות קיימות **רק** כדי לקנות
 * חלופות לפריט קצר. השורות נגזרות מהיחס ומתקציב הפיקסלים בלבד.
 */
export const MAX_CANDIDATES = 6;

/**
 * כמה מותר ליחס המצויר לסטות מזה שהוזמן, כששורה נוספת קונה חלופה נוספת. 10%.
 *
 * **סטייה כזו קיימת כאן ממילא.** `rowsPerColumn` מעגל, כלומר הוא כבר מקבל חצי
 * שורה של טעות: בקנבס לאורך זה ±0.28 ביחס (±3.3% על צמיד ביחס 8.3), ובקנבס
 * לרוחב ±0.63. מה שלא היה קיים הוא **הצהרה** על גודל הטעות — ולכן גם לא היה
 * אפשר לשאול "מה עוד אפשר לקבל בתוכה".
 *
 * זה מה שהמספר הזה עושה: הוא הופך את טווח הטעות מתוצר לוואי של עיגול להחלטה,
 * ולוקח בתוכו כל שורה שאפשר. הרווח כולו נופל על הקנבס לאורך, וזה בדיוק המקום
 * שהוא נבנה בשבילו: שם שורה שווה 0.556 ביחס, ולכן בתוך 10% נכנסות עוד אחת או
 * שתיים. לרוחב שורה שווה 1.25 — יותר מ-10% כמעט תמיד — ולכן שם שום דבר לא זז,
 * וזה הנכון: זה הקנבס שבו הגובה באמת נלחץ.
 *
 * ⚠ הסטייה נמדדת מול `NATURAL_RATIO`, שהוא קו שהותאם ל-45 הרצות **לרוחב בלבד**,
 * בטווח יחסי-תא 1.5–9. שתי השורות הראשונות לאורך (תא 0.667 ו-1.33) יושבות
 * מתחת לטווח שנמדד, כלומר החיזוי שם הוא הארכה. אם המודל דווקא מצייר שם את היחס
 * הטבעי שלו (~6.5) בלי להיות מושפע מהתא — וזה הסביר, כי בתא כזה הפריט רחוק
 * מלמלא את הגובה — השורה הנוספת חינמית **עוד יותר** ממה שהמספר כאן מניח. הקנס
 * שמחושב הוא הרע מבין השניים, ולכן זה הכיוון הבטוח לטעות בו.
 */
const RATIO_SLACK = 0.1;

/**
 * כמה פיקסלים הפתח הקטן ביותר חייב לתפוס כדי לשרוד. מתחת לזה הוא נסגר
 * בקונדישנינג או מתמזג עם שכנו, והשורה נפסלת ב-V5 — כלומר שורה שנוספה כדי לתת
 * עוד חלופה מחזירה חלופה שאי אפשר לייצר.
 */
const MIN_FEATURE_PX = 3;

export interface PlanInput {
  /** אורך/רוחב של הפריט שהוזמן. */
  ratio: number;
  /** רוחב הפריט במ"מ — הוא שנפרס על גובה השורה. */
  widthMm: number;
  /** הפתח הקטן ביותר שאפשר לחתוך, במ"מ (resolveFab). */
  minHoleMm: number;
  /** צורת הקנבס שיתבקש. ברירת מחדל: לרוחב — ההתנהגות שהייתה תמיד. */
  canvas?: Canvas;
}

export interface RenderPlan {
  /** שורות בתמונה. מספר החלופות הוא rows × cols. */
  rows: number;
  /** עמודות בתמונה. 1 לפריט ארוך; 2 כשהפריט קצר מספיק (טבעת) והשורות לבדן
   *  מחזירות פחות חלופות ממה שהמסך מציג. */
  cols: number;
  /** תמיד 1. נשאר בחוזה כי הקופסה והיומן מדווחים אותו. */
  calls: 1;
  /** כמה פסים ייחתכו מהתמונה — `rows × cols`. זה מה שהקופסה מייצרת. */
  candidates: number;
  /**
   * כמה מהם מוצעים ללקוחה. `min(candidates, MAX_CANDIDATES)`.
   *
   * נפרד מ-`candidates` מאז 11.8: הייצור נגזר מהיחס ומתקציב הפיקסלים, והתצוגה
   * מכמה חלופות אפשר להעמיד מול לקוחה בלי להפוך בחירה לרשימה. פריט צר מייצר
   * הרבה ומציע שישה — והשישה נבחרים לפי מי שקרוב ביותר ליחס שהוזמן
   * (`render/ratioGap`), כלומר מי שיצטרך את המתיחה הקטנה ביותר.
   */
  offered: number;
  /** הקנבס שהתכנון נעשה עבורו. הקופסה והיומן מדווחים אותו. */
  canvas: Canvas;
}

/**
 * התקרה על מספר השורות. **לא מספר שנבחר אלא תקציב פיקסלים**: ככל שיש יותר
 * שורות כל פריט מקבל פחות גובה, ובשלב מסוים הפתח המינימלי קטן מכדי לשרוד את
 * המעקב. אם נעבור אי פעם לקנבס גדול יותר, התקרה תעלה מעצמה.
 *
 * בפועל היא כמעט לא נוגעת: פריט רחב (שבו התקרה נמוכה) הוא גם פריט ביחס נמוך,
 * שממילא מבקש מעט שורות. היא נועדה למקרה הקצה, לא לניהול היומיום.
 */
export function maxRows(widthMm: number, minHoleMm: number, canvas: Canvas = LANDSCAPE): number {
  const pxPerMmAtOneRow = (canvas.heightPx * ROW_FILL) / widthMm;
  return Math.max(1, Math.floor((pxPerMmAtOneRow * minHoleMm) / MIN_FEATURE_PX));
}

/**
 * התקרה על מספר העמודות, ואותו תקציב פיקסלים במאונך לו: הפריט נפרס על רוחב
 * העמודה, ולכן ככל שיש יותר עמודות כל פריט מקבל פחות פיקסלים **לאורכו**.
 *
 * שני חסמים, והשני הוא העיקר. הראשון הוא אותו מינימום כמו בשורות: פתח שלא שורד
 * את המעקב. הוא נמדד מול MIN_FEATURE_PX ומתיר, על צמיד ארוך, עמודה שנייה שנוגעת
 * בדיוק בקצה — 3.2 פיקסלים לפתח. רף הישרדות אינו רף איכות.
 *
 * לכן החסם השני: עמודה נוספת מותרת רק כל עוד כל פריט מקבל **לפחות** את צפיפות
 * הפיקסלים שצמיד באורך ברירת המחדל מקבל היום בעמודה אחת. זה בדיוק הטיעון שבגללו
 * העמודות אפשריות: הן נמדדות מול אורך הפריט, וטבעת קצרה. ‎55 מ"מ על חצי קנבס הם
 * יותר פיקסלים למ"מ מ-‎160 מ"מ על קנבס שלם, ולכן העמודה השנייה בטבעת לא רק שאינה
 * פוגעת באיכות — היא נשארת מעליה. על צמיד באורך מלא אין מרחק כזה, והחסם מחזיר 1.
 */
export function maxCols(lengthMm: number, minHoleMm: number, canvas: Canvas = LANDSCAPE): number {
  const pxPerMmAtOneCol = (canvas.widthPx * COL_FILL) / lengthMm;
  const feature = Math.floor((pxPerMmAtOneCol * minHoleMm) / MIN_FEATURE_PX);
  // זהה ל-`floor(defaultLengthMm / lengthMm)` בקנבס לרוחב, ונכון גם באחר.
  const density = Math.floor(pxPerMmAtOneCol / REFERENCE_PX_PER_MM);
  return Math.max(1, Math.min(feature, density));
}

/**
 * שורות שאינן עולות דבר ברזולוציה.
 *
 * הפריט מצויר בקנה מידה אחיד `min(לאורך, לרוחב)`. כל עוד ציר האורך הוא החסם,
 * שורה נוספת מצמצמת את גובה התא אבל **לא נוגעת בקנה המידה** — הפריט מצויר
 * באותה רזולוציה בדיוק. רק כשרוחב הפס הופך לחסם מתחילים לשלם.
 *
 *     (גובה·ROW_FILL)/שורות / רוחב_הפס  ≥  (רוחב·FILL)/אורך
 *
 * נמדד ב-AP-0065 (104.4×40, לאורך): שורה אחת ושתיים נותנות **8.83 px/mm שתיהן**,
 * ורק השלישית יורדת ל-6.40.
 */
function freeRows(lengthMm: number, widthMm: number, canvas: Canvas): number {
  const alongLength = (canvas.widthPx * COL_FILL) / lengthMm;
  return Math.max(1, Math.floor((canvas.heightPx * ROW_FILL) / (widthMm * alongLength)));
}

/**
 * השורות שאפשר להוסיף מעל מה שהיחס דורש, בלי לצאת מ-`RATIO_SLACK`.
 *
 * עולים שורה-שורה ועוצרים בראשונה שיוצאת מהטווח — ולא קופצים ישר לתקרה — כי
 * הפונקציה מונוטונית מ-`wanted` והלאה (כל שורה מרחיקה את היחס החזוי), ולכן
 * השורה הראשונה שנפסלה פוסלת גם את כל מה שמעליה.
 */
function rowsWithinSlack(ratio: number, canvas: Canvas, from: number, ceiling: number): number {
  let rows = from;
  while (rows + 1 <= ceiling && Math.abs(NATURAL_RATIO(rows + 1, 1, canvas) - ratio) / ratio <= RATIO_SLACK) {
    rows += 1;
  }
  return rows;
}

/**
 * מתכנן הרצה: כמה פריטים בתמונה, בקריאה אחת.
 *
 * היחס קובע את **צורת התא** ולא את מספר השורות: שורות לעמודה הן `rowsPerColumn`,
 * וכל עמודה נוספת מכפילה איתן את השורות כדי לשמור על אותה צורה. פריט ארוך מגיע
 * לחלופות דרך שורות ונשאר בעמודה אחת; פריט קצר, שהשורות לבדן מחזירות לו חלופה
 * אחת, מקבל עמודה שנייה — אותה קריאה, אותו יחס, ארבע חלופות במקום אחת.
 *
 * **מתחת למחובר (יחס < 5.3) אין תשובה נכונה, ולכן לוקחים את מה שבחינם.**
 * `rowsPerColumn` מחזיר שם מספר שלילי — לא "שורה אחת" אלא "פחות משורה אחת",
 * כלומר בקשה שאי אפשר לנסח. עד כה ה-`max(1, …)` הפך את זה ל-1, וזה היה שומר
 * מפני מספר לא חוקי ולא הכרעה: פריט רחב קיבל חלופה אחת בזמן שתקציב הפיקסלים
 * הרשה יותר **באותה רזולוציה בדיוק**. עכשיו הוא מקבל את השורות שאינן עולות
 * דבר. השורה שכן תעלה — לא נלקחת.
 *
 * **ומעל המחובר: היחס הוא רצפה, לא תקרה.** עד כאן `rowsPerColumn` היה גם
 * התשובה הסופית, ולכן פריט שהיחס שלו נפל בין שתי שורות קיבל חלופה אחת בזמן
 * ששאר הקנבס נשאר לבן — נראה על עיצוב 90. זה לא היה מחיר של דיוק אלא של עיגול:
 * הטעות המותרת (חצי שורה) הייתה שם ממילא, פשוט לא נוצלה. מכאן היא מוצהרת
 * (`RATIO_SLACK`) ונלקחת עד הסוף — כל שורה שנשארת בתוכה **ושאינה עולה דבר
 * ברזולוציה** (`freeRows`) נוספת.
 *
 * הרווח נופל כולו על הקנבס לאורך, ששם שורה שווה 0.556 ביחס: 120×20 עולה
 * מחלופה אחת לשתיים, 130×18 משלוש לארבע, 150×18 מחמש לשש. לרוחב שורה שווה
 * 1.25, שהם יותר מ-10% כמעט בכל יחס — ולכן שם התכנון לא זז בכלל.
 *
 * **ומ-11.8: ייצור ותצוגה נפרדים.** השורות נגזרות מהיחס ומתקציב הפיקסלים
 * בלבד; `MAX_CANDIDATES` — תקרה שנכתבה על כמה חלופות המסך מציג — כבר לא חותך
 * אותן. הוא חל על `offered` (כמה מהפסים מוצעים לבחירה) ועל העמודות, שקיימות
 * ממילא רק כדי לקנות חלופות לפריט קצר. פריט צר וארוך מייצר עכשיו את מה שהיחס
 * דורש ומציע שישה מתוכו — במקום לצייר שישה ביחס שאינו שלו ולמתוח את התוצאה.
 */
export function planRender({ ratio, widthMm, minHoleMm, canvas = LANDSCAPE }: PlanInput): RenderPlan {
  const lengthMm = ratio * widthMm;
  const rowCap = maxRows(widthMm, minHoleMm, canvas);
  const colCap = maxCols(lengthMm, minHoleMm, canvas);
  const wanted = rowsPerColumn(ratio, canvas);
  const free = freeRows(lengthMm, widthMm, canvas);
  // התקרה על השורות. `MAX_CANDIDATES` חל גם עליהן: עד כה הוא נאכף **רק** בלולאת
  // העמודות, ולכן פס צר וארוך פרץ אותו דרך השורות בלבד — 125×10 נתן 6 לרוחב
  // (במקרה בדיוק על הגבול) ו-12 לאורך. שתים־עשרה רצועות מלאות־רוחב אחת מתחת
  // לשנייה אינן בחירה אלא רשימה, וזו בדיוק הסיבה שהתקרה נכתבה.
  //
  // ‏`free` נכנס לתקרה **רק** כרשות להוסיף מעבר למה שהיחס דרש: שורה שנלקחת בשם
  // חלופה נוספת חייבת להיות חינמית גם ברזולוציה, לא רק ביחס. שורה שהיחס עצמו
  // דורש (`wanted`) נלקחת בכל מקרה — שם `rowCap`, ששומר על הישרדות הפתח, הוא
  // הגבול הנכון.
  //
  // **`MAX_CANDIDATES` יצא מכאן** (11.8). הוא ישב באותו `min`, ולכן תקרה שנכתבה
  // על "כמה חלופות המסך מציג" קבעה גם את צורת התא — כלומר את היחס שהמודל
  // מצייר. מה שנשאר הוא `rowCap`, שהוא הגבול האמיתי: מעליו הפתח המינימלי לא
  // שורד את המעקב. כמה מהפסים יוצעו ללקוחה נחתך בנפרד, ב-`offered`.
  //
  // המחיר ברזולוציה קטן ממה שהוא נשמע: `freeRows` הוא המספר שעד אליו שורה
  // אינה עולה **כלום** — הפריט מצויר בקנה מידה `min(לאורך, לרוחב)`, ובפריט צר
  // וארוך ציר האורך הוא החסם הרבה אחרי שהשורות נגמרו. ב-AP-0096: 24 שורות
  // חינם, ותקרת ההישרדות 25.
  const ceiling = Math.min(rowCap, Math.max(wanted, free));
  const perColumn = Math.min(
    // מתחת למחובר אין יחס להגן עליו (ראה התיעוד), ולכן שם נלקח מה שחינמי; מעליו
    // היחס הוא הרצפה, ומעליה נלקחת כל שורה שנשארת בתוך `RATIO_SLACK`.
    wanted >= 1 ? rowsWithinSlack(ratio, canvas, wanted, ceiling) : free,
    ceiling,
  );

  let cols = 1;
  while (
    perColumn * cols * cols < TARGET_CANDIDATES &&
    cols + 1 <= colCap &&
    perColumn * (cols + 1) <= rowCap &&
    perColumn * (cols + 1) * (cols + 1) <= MAX_CANDIDATES
  ) {
    cols += 1;
  }

  const rows = perColumn * cols;
  const candidates = rows * cols;
  return {
    rows,
    cols,
    calls: 1,
    candidates,
    offered: Math.min(candidates, MAX_CANDIDATES),
    canvas,
  };
}
