// צורת הקנבס שמודל התמונה מצייר עליו, וההחלטה איזו צורה לבקש.
//
// עד כה היה קנבס אחד — 1536×1024 — ולכן הוא ישב כקבוע בארבעה מקומות. הוא הפך
// לפרמטר כי צורת הקנבס היא **הידית היחידה** על היחס שהמודל מצייר: כשמבקשים
// ממנו לחלק את התמונה ל-N שורות, כל שורה היא תא, והוא ממלא אותו.
//
//     יחס התא = (רוחב/גובה הקנבס) · שורות/עמודות
//     יחס מצויר ≈ 5.3 + 0.833 · יחס התא         (נמדד, panels.ts)
//
// לרוחב, יחס הקנבס הוא 1.5 ולכן כל שורה שווה 1.25 ביחס. לאורך הוא 0.667 וכל
// שורה שווה 0.556 — צעדים עדינים פי 2.25, וטווח נמוך יותר. פריט ביחס נמוך
// (צמיד רחב, פריט קצר) לא מגיע לחלופות בקנבס לרוחב: הוא מבקש פחות משורה אחת.
//
// ⚠ המחיר: הציר הארוך של הפריט מקבל 1024 פיקסלים במקום 1536. ראו
// `portraitBandMm` למטה — הפס נקבע מזה ולא מהעדפה.

/** יחס הצדדים של הקנבס. 1.5 לרוחב, 0.667 לאורך. */
export interface Canvas {
  widthPx: number;
  heightPx: number;
}

export const LANDSCAPE: Canvas = { widthPx: 1536, heightPx: 1024 };
export const PORTRAIT: Canvas = { widthPx: 1024, heightPx: 1536 };

export const aspect = (c: Canvas): number => c.widthPx / c.heightPx;

/** `1536x1024` — הצורה שבה מודל התמונה מקבל את הגודל. */
export const sizeParam = (c: Canvas): string => `${c.widthPx}x${c.heightPx}`;

/**
 * הפס שבו קנבס לאורך נבחר, במ"מ של אורך הפריסה. שני הגבולות נגזרים ולא נבחרו:
 *
 * **80.1 בתחתית** — מתחת ל-80 מ"מ הפריט כבר מקבל עמודה שנייה בקנבס לרוחב
 * (`maxCols`), וארבע חלופות. אין מה לקנות שם.
 *
 * **153.2 בקצה** — הציר הארוך לאורך הוא `1024 · 0.9` = 921.6 פיקסלים. הפתח
 * הקטן ביותר (0.5 מ"מ) חייב 3 פיקסלים כדי לשרוד את המעקב, כלומר 6 px/mm,
 * כלומר `921.6/6` = 153.6 מ"מ. 153.2 משאיר מרווח של 0.4 מ"מ — **מרווח דק
 * מאוד**, וזו הסיבה שהמנגנון כולו מאחורי מתג.
 *
 * ⚠ בפס הזה הצפיפות נמוכה מזו של היום: 7.37 px/mm ב-125 מ"מ ו-6.02 ב-153.2,
 * מול 8.64 שצמיד באורך ברירת המחדל מקבל. **אף הרצה מעולם לא רצה מתחת ל-8.53**
 * (27 הרצות ביומן), ולכן זה תחום שלא נמדד בו דבר. המדד שכן נמדד — IoU — לא
 * התקרב לשער בשום הרצה (הנמוך ביותר 0.8925 מול שער 0.75), אבל הסיכון כאן אינו
 * IoU אלא הישרדות הפתח, שהיא בינארית.
 */
export const PORTRAIT_BAND_MM: [number, number] = [80.1, 153.2];

/**
 * מתג ההפעלה. **כבוי כברירת מחדל**, ובכוונה.
 *
 * הקופסה (`vec.rmjewel.com`) נפרסת בנפרד מהאפליקציה. אם האפליקציה תבקש קנבס
 * לאורך בזמן שהקופסה עוד לא יודעת לקבל את הפרמטר, היא תרנדר לרוחב בזמן
 * שתמונת הייחוס נבנתה לאורך — כלומר רגרסיה לכל הפס, שהוא רוב הצמידים.
 * המתג מבטיח שהמיזוג לא משנה דבר עד שהקופסה למעלה.
 *
 * להפעלה: `PORTRAIT_CANVAS=1`. לחזרה אחורה: להסיר. אין צורך ב-revert.
 */
export const portraitEnabled = (): boolean => process.env.PORTRAIT_CANVAS === "1";

/**
 * הקנבס לפריט באורך נתון. `enabled` נמסר במפורש כדי שהבחירה תהיה ניתנת
 * לבדיקה בלי לגעת בסביבה.
 */
export function canvasFor(lengthMm: number, enabled = portraitEnabled()): Canvas {
  if (!enabled) return LANDSCAPE;
  const [lo, hi] = PORTRAIT_BAND_MM;
  return lengthMm >= lo && lengthMm <= hi ? PORTRAIT : LANDSCAPE;
}
