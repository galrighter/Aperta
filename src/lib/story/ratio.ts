import type { ProductType } from "@/lib/fabrication.config";
import { LANDSCAPE, PORTRAIT, aspect, portraitEnabled, type Canvas } from "@/lib/render/canvas";

// story mode — היחס בין אורך לרוחב: מה מבקשים, ומה התצורה שמסוגלת לתת אותו.
//
// **למה זה קיים בכלל.** במסלול Story הרוחב אינו נבחר — הוא נגזר מהיחס שהמודל
// צייר (`storyFrameDims`). כלומר **היחס הוא הרוחב**, וכל דיון על "הפריט יצא
// רחב מדי" הוא דיון על המספר הזה ועל שום דבר אחר.
//
// עד כאן איש לא ביקש אותו. הפרומפט של המסלול אמר "פרופורציות אמינות" והשאיר
// את ההכרעה למודל, ומה שיצא נמדד (13 הרצות ביומן, 13–16.8): טבעת במידה 8.5
// יצאה ביחס 2.47 — 25 מ"מ רוחב, מול טווח מוצר מוצהר של 4–18 — וצמיד יצא
// ב-2.45, כלומר 65 מ"מ. מכאן שני הדברים שהקובץ הזה מחזיק: הטווח שמותר לבקש,
// והתרגום מ"מה ביקשנו" ל"איזו תצורה לשלוח".

/* ===== 1. הטווח שמותר לבקש ===== */

/**
 * הטווח לכל מוצר, מהרחב לדק — **החלטת גל, 16.8**.
 *
 * ריכזתי אותו כאן ולא ב-`fabrication.config` בכוונה: זו אינה מגבלת ייצור אלא
 * החלטת מוצר. הייצור מוגן במקום שהוא תמיד היה מוגן בו — הוולידציה — ומה
 * שנקבע כאן הוא מה ש**מבקשים**, לא מה שמותר לחתוך.
 *
 * ⚠ **הקצה הדק של הצמיד לא נמדד מעולם ולא ידוע אם הוא בהישג יד.** לפי הכיול
 * למטה, יחס 47.5 דורש תא של 69:1 — כ-45 שורות בקנבס לרוחב, מספר שאינו קיים.
 * הוא נשאר כאן כפי שנקבע: תפקיד הטווח הוא להגדיר את הרצוי, ותפקיד המדידה
 * (`askedRatios` מול `drawnRatio` ביומן) הוא לומר עד לאן באמת מגיעים. חיתוך
 * הטווח למה שנוח היום היה מוחק בדיוק את השאלה.
 */
export const RATIO_BAND: Record<ProductType, [number, number]> = {
  // רחב 2.9 → 21 מ"מ במידה 8.5 · דק 12.25 → 4.9 מ"מ
  ring: [2.9, 12.25],
  // רחב 2.4 → 67 מ"מ על פרק 165 · דק 47.5 → 3.3 מ"מ
  bracelet: [2.4, 47.5],
};

/**
 * הרוחב שמתחתיו לא יורדים, ומה קורה כשהיחס מבקש לרדת: **היחס משתנה, לא הרוחב**
 * (החלטת גל).
 *
 * הכיוון הזה חשוב. צביטת הרוחב אחרי שהעיצוב צויר הייתה מחזירה בדיוק את המתיחה
 * האופקית שכל המסלול הזה בא למנוע (ראה `storyFrameDims`) — הצורה הייתה נדחסת
 * בציר אחד. הצבת גבול על **מה שמבקשים**, לפני הציור, נותנת את אותה הגנה בלי
 * לגעת בצורה בכלל: המודל מצייר יחס שאפשר לחיות איתו מלכתחילה.
 *
 * אלה אינם ספי ייצור — הוולידציה מתירה הרבה מתחתיהם (צוואר 0.75, פתח 0.5) —
 * אלא הרוחב שמתחתיו כבר אין מקום לעיצוב על הפריט.
 *
 * **טבעת 2 · צמיד 3.5 — החלטת גל, 16.8**, אחרי מדידת הצר ביותר ב-81 המועמדים
 * השמורים: בטבעת החציון 4.72 והקיצון 2.46, בצמיד החציון 13.84 והקיצון 4.42.
 * המספר היה 3 לשניהם, וההפרדה היא ההכרה בכך שטבעת **צריכה** להיות צרה יותר.
 */
export const MIN_WIDTH_MM: Record<ProductType, number> = {
  ring: 2,
  bracelet: 3.5,
};

/**
 * הטווח בפועל לפריט באורך נתון: הקצה הדק נחתך ברוחב המינימלי.
 *
 * בצמיד זה נוגע: כבר באורך העוגן (160.4) יחס 47.5 נותן 3.38 מ"מ, מתחת ל-3.5,
 * והתקרה יורדת ל-45.8; בפרק יד קטן (פריסה ~132) היא יורדת ל-37.7. בטבעת זה
 * לא נוגע — גם במידה 1, הקטנה בטבלה, היחס 12.25 נותן 3.25 מ"מ, הרבה מעל 2.
 * כלומר בטבעת הרצפה היא רשת ביטחון שלא נופלים עליה, ובצמיד היא גבול פעיל.
 *
 * בלי אורך (לא אמור לקרות ביצירת Story, אבל הטיפוס מתיר) מוחזר הטווח כמות שהוא.
 */
export function ratioBandFor(product: ProductType, lengthMm?: number): [number, number] {
  const [wide, thin] = RATIO_BAND[product];
  if (!lengthMm || !(lengthMm > 0)) return [wide, thin];
  const thinnest = lengthMm / MIN_WIDTH_MM[product];
  return [wide, Math.min(thin, Math.round(thinnest * 10) / 10)];
}

/* ===== 2. איזו תצורה נותנת איזה יחס ===== */

/**
 * היחס שהמודל מצייר בפועל, כפונקציה של צורת התא — **מכויל מחדש למסלול
 * הדו-שלבי**.
 *
 * ‏`NATURAL_RATIO` ב-render/panels.ts הוא `5.3 + 0.83·יחס-התא`, והוא נמדד על
 * 45 הרצות של הפרומפט של **שלב אחד**. הוא עדיין נכון שם. הוא אינו נכון כאן:
 * מאז שהסיפור עובר דרך מודל טקסט שמחזיר הוראות ציור, מודל התמונה מצייר הרבה
 * יותר רחב. 11 ההרצות הדו-שלביות ביומן (14–16.8), ממוצע המועמדים בכל אחת:
 *
 *     קנבס לאורך, 3 שורות  (תא 2.0)  →  2.26 · 2.75            ממוצע 2.51
 *     קנבס לרוחב, 3 שורות  (תא 4.5)  →  5.22 · 4.55 · 3.48 · 3.50   ממוצע 4.19
 *
 * ישר דרך שתי הנקודות: שיפוע 0.67, חותך 1.16. החותך צנח מ-5.3 ל-1.16, וזה
 * ההסבר המספרי לכך ש"כל העיצובים יוצאים רחבים".
 *
 * ⚠ **שתי נקודות בלבד, ומהן הראשונה נשענת על שתי הרצות.** זה כיול ראשוני
 * שנועד להחליף ניחוש, לא מדידה סגורה. הוא נבדק מול עצמו בכל הרצה: `askedRatios`
 * נשמר לצד `drawnRatio`, והפער ביניהם הוא מה שיתקן את שני המספרים כאן.
 */
export const STORY_RATIO_INTERCEPT = 1.16;
export const STORY_RATIO_PER_CELL = 0.67;

/** היחס שתצורה נתונה מושכת אליו. `יחס-התא = יחס-הקנבס · שורות/עמודות`. */
export const storyNaturalRatio = (rows: number, canvas: Canvas, cols = 1): number =>
  STORY_RATIO_INTERCEPT + (STORY_RATIO_PER_CELL * aspect(canvas) * rows) / cols;

/** התצורה שנשלחת למודל התמונה. `cols` נשאר 1 — ראה `storyLayoutFor`. */
export interface StoryLayout {
  rows: number;
  cols: 1;
  canvas: Canvas;
  /** מה שהתצורה הזו מבטיחה, לפי הכיול. נשמר ביומן מול מה שיצא. */
  naturalRatio: number;
}

/**
 * החציון. מרכז ולא ממוצע: כשמבקשים בכוונה דוגמה אחת קיצונית (וזה בדיוק מה
 * שנתבקש — "לפחות אחת דקה"), ממוצע נגרר אחריה ומזיז את התצורה של כולן.
 */
export function centerRatio(ratios: number[]): number {
  const sorted = [...ratios].sort((a, b) => a - b);
  const mid = sorted.length >> 1;
  return sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
}

/**
 * התצורה שתשלח למודל התמונה, מתוך היחסים שמודל הטקסט ביקש.
 *
 * **שורות = מספר העיצובים.** כל עיצוב הוא שורה, ולכן מספר השורות אינו נתון
 * לבחירה נפרדת — הוא מה שמודל הטקסט החזיר. זה גם מה שנותן את הקשר שגל ביקש:
 * מנה דקה יותר מצדיקה יותר שורות, יותר שורות הן יותר חלופות, ושתי התכונות
 * נופלות מאותה החלטה במקום להיות שני מנגנונים.
 *
 * **הקנבס הוא הידית שנשארת.** בהינתן מספר השורות, שתי צורות הקנבס מציעות שני
 * יחסים שונים (ב-3 שורות: 2.5 לאורך מול 4.2 לרוחב), ונבחרת זו שקרובה יותר
 * למרכז המבוקש. עמודות אינן משתתפות: הן מחלקות את יחס התא, כלומר מושכות
 * לכיוון **רחב**, וזה הכיוון היחיד שאין בו מחסור.
 *
 * ⚠ מה שהתצורה נותנת הוא **משיכה, לא כלוב**. חשבתי בהתחלה שמספר השורות מציב
 * רצפה קשיחה על היחס (פריט לא יכול להיות רחב מגובה השורה שלו), והיומן סותר
 * את זה: בקנבס לרוחב עם 3 שורות, שרצפתו כביכול 4.05, נמדדו 3.19 ו-2.97.
 * המודל פשוט מקטין את הפריט כדי שייכנס. לכן הקנבס קובע לאן **מושכים**, ולא
 * מה מתאפשר — ומה שיוצר את הפיזור סביב המרכז הוא הניסוח.
 */
export function storyLayoutFor(
  ratios: number[],
  enabled = portraitEnabled(),
): StoryLayout {
  const rows = Math.max(1, ratios.length);
  const options = enabled ? [PORTRAIT, LANDSCAPE] : [LANDSCAPE];
  const target = centerRatio(ratios);
  let best = options[0];
  for (const c of options) {
    const gap = Math.abs(storyNaturalRatio(rows, c) - target);
    if (gap < Math.abs(storyNaturalRatio(rows, best) - target)) best = c;
  }
  return { rows, cols: 1, canvas: best, naturalRatio: storyNaturalRatio(rows, best) };
}
