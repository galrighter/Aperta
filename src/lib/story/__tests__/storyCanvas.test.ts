import { describe, expect, it } from "vitest";
import { storyCanvas } from "../mode";
import { LANDSCAPE, PORTRAIT, canvasFor } from "@/lib/render/canvas";

/**
 * story mode — הקנבס קבוע, ולאורך.
 *
 * **למה זה נבדק ולא רק נכתב.** ההבדל בין קבוע לנגזר אינו נראה בקוד שרץ: שתי
 * ההתנהגויות מחזירות `Canvas` תקין, והתמונה חוזרת בשני המקרים. הוא נראה רק
 * בקצוות — פריט שהאורך שברשומה מציב אותו בפס של `canvasFor` מול פריט שמחוצה
 * לו — ושם ההבדל הוא בין "אותה צורה לכל הרצות המסלול" לבין "צורה שנקבעת לפי
 * אורך ברירת המחדל שהרשומה נפתחה בו", כלומר לפי מספר שאיש לא בחר.
 */

describe("storyCanvas", () => {
  it("לאורך — ולא תלוי באורך שברשומה", () => {
    expect(storyCanvas()).toEqual(PORTRAIT);
  });

  /**
   * הטענה בצורתה החדה: באורך ברירת המחדל של צמיד (160 מ"מ) `canvasFor` מחזיר
   * **לרוחב** — הוא מחוץ לפס — ובכל זאת המסלול שולח לאורך. אם מישהו יחזיר כאן
   * את הגזירה, הבדיקה הזו היא זו שתיפול.
   */
  it("שונה מ-`canvasFor` בדיוק במקום שבו זה משנה", () => {
    expect(canvasFor(160)).toEqual(LANDSCAPE);
    expect(storyCanvas()).not.toEqual(canvasFor(160));
  });

  /**
   * `PORTRAIT_CANVAS=0` הוא חוזה תפעולי ולא העדפה: הוא נכתב כדי שאפשר יהיה
   * לחזור מקנבס לאורך בלי revert ובלי פריסה מחדש. צרכן חדש של לאורך שמתעלם
   * ממנו הופך אותו לחצי ידית, בדיוק ברגע שמושכים אותה.
   */
  it("כיבוי החירום חולש גם על המסלול הזה", () => {
    expect(storyCanvas(false)).toEqual(LANDSCAPE);
  });
});
