-- תמונת התצוגה המקדימה של שיתוף — צילום של ההדמיה התלת־ממדית.
--
-- עד כה `og:image` הצביע על `render_path`: ההדמיה שמודל התמונה ייצר. שתי בעיות,
-- ושתיהן נמדדו על לינק אמיתי:
--
-- 1. **משקל.** זה PNG של 1536x1024 ישר ממודל תמונה. וואטסאפ מוותר על תצוגה
--    מקדימה מעל כמה מאות KB, ובפועל הלינק הגיע בלי תמונה בכלל.
-- 2. **זה לא הפריט.** התמונה ההיא היא מה שהמודל צייר לפני שהווקטורייזר גזר
--    ממנה חיתוכים — הקלט לצינור, לא הפלט שלו. מה שהלקוחה רואה על המסך ומה
--    שנחתך במתכת הוא ההדמיה התלת־ממדית.
--
-- הצילום נלקח מהקנבס בדפדפן ברגע השיתוף ונשמר כ-JPEG: עשרות KB במקום מגה־בייטים,
-- ובדיוק מה שהיה על המסך.
--
-- העמודה נוספת ואינה מחליפה: שיתוף שנוצר בלי קנבס פעיל (הסטודיו בטאב הפריסה)
-- נשאר עם `render_path`, ומי שאין לו גם את זה נופל לתמונת ברירת המחדל של האתר.

alter table design_shares add column if not exists preview_path text;

comment on column design_shares.preview_path is
  'צילום ההדמיה התלת־ממדית ב-storage (JPEG). קודם ל-render_path כתמונת השיתוף.';

