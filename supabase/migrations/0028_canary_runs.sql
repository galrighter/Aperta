-- לקנרית יש מקור משלה ביומן.
--
-- עד כאן היצירה הסינתטית של canary.yml נכתבה ל-generation_runs כ-`studio` —
-- כלומר כמו יצירה של לקוחה. בשבוע שקדם ל-17.8 זה היה **79 מתוך 166 ההרצות**:
-- כמעט חצי מהיומן, כולן על אותו תיאור קבוע, כולן בלי בעלים (העיצוב נמחק בסוף
-- ההרצה ולכן גם ה-`ref` ריק). מי שנכנס ליומן בעקבות תלונה סרק אותן בעיניים
-- בדרך לשורה שהוא חיפש — וזה בדיוק סוג הרעש שמאמן לדלג על שורות.
--
-- הסימון כאן הוא שני דברים בלבד: ערך מותר חדש, והסבה של ההיסטוריה. **המחיקה
-- אינה כאן** אלא בקוד (src/lib/runs/canary.ts): לשורת יומן יש תמונות ב-storage
-- ולעתים שורת job לצדה, ו-`delete` בודד היה משאיר בייטים שאיש כבר לא יכול
-- להגיע אליהם ושורת job יתומה — שהיומן מציג כ"ניסיון שלא הגיע לשורת הרצה",
-- כלומר אותו רעש בדיוק במסווה אחר (ראה src/lib/runs/orphans.ts).

-- הערך המותר. ה-check של 0003 אינו קיים בפרודקשן (הטבלה עברה שם דרך 0007
-- ואיבדה אותו), ולכן `drop ... if exists` ואז הוספה: מסד טרי ומסד קיים
-- מתכנסים לאותה הגדרה, ושתי ההרצות בטוחות — migrate מריץ את כל הקבצים בכל
-- פריסה.
alter table generation_runs drop constraint if exists generation_runs_source_check;
alter table generation_runs add constraint generation_runs_source_check
  check (source in ('studio', 'debug', 'upload', 'canary'));

-- ההיסטוריה. הזיהוי הוא התיאור הקבוע שה-workflow שולח — הוא הדבר היחיד ששרד
-- על השורות האלה, כי העיצוב שלהן כבר נמחק. 79 שורות ענו לו ב-17.8, וכולן
-- קנריות: ארבע מהן עוד מצביעות על עיצוב קיים בשם `canary` תחת פרופיל בודק,
-- ו-75 מצביעות על עיצוב שנמחק.
--
-- **חסום בתאריך**, ולא רק בתיאור. הקובץ הזה ירוץ שוב בכל פריסה עתידית, ובלי
-- הגבול העליון לקוחה שתכתוב במקרה בדיוק את המשפט הזה הייתה מקבלת הסבה ומחיקה
-- של ההרצה שלה. מרגע שהקוד באוויר הקנרית מסמנת את עצמה (`source: 'canary'`
-- מ-/api/generate), ולכן לחלון הזה אין המשך — הוא רק מכסה את הפער בין המיזוג
-- לפריסה.
update generation_runs
   set source = 'canary'
 where source = 'studio'
   and prompt = 'עיגולים חופפים בגדלים שונים לאורך הצמיד'
   and created_at < timestamptz '2026-08-24 00:00:00+00';

-- הסבב הראשון של המחיקה יעבור על כל אלה: השורות שהצליחו יימחקו עם התמונות
-- שלהן, ומה שנכשל יישאר — הכישלון של הקנרית הוא הדבר היחיד שהיא קיימת בשבילו.
create index if not exists idx_generation_runs_source on generation_runs(source);
