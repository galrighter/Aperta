-- ההצעות שמוצגות ללקוחה שורדות רק בזיכרון הדפדפן.
--
-- `/api/generate` מייצר כמה הצעות, שומר את הטובה כגרסה, ומחזיר את השאר בגוף
-- התשובה בלבד. הן לא נכתבות לשום מקום. התוצאה: כל רענון דף, וכל פתיחה של
-- עיצוב שמור, מוחקים אותן — `resume` בונה את הגרסאות מה-DB ואין שם `candidates`,
-- כך ש-`picks` יוצא ריק והרצועה נעלמת בלי הסבר. הלקוחה ראתה ארבע חלופות,
-- רועננה, ונשארה עם אחת.
--
-- שלוש עמודות, לא שלוש טבלאות: ההצעות הן נספח לגרסה שאיתה נולדו, ולא ישויות
-- בפני עצמן. החלופה — שורת גרסה לכל הצעה — נשקלה ונדחתה: היא דורשת שהיומן
-- ילמד לקבץ אחיות, אחרת שלוש הצעות נראות כשלושה שינויים, וזה בדיוק הבלבול
-- שנסגר ב-#104.
alter table design_versions
  -- ההצעות שהוצעו יחד עם הגרסה הזו: [{ svg, report, drawnRatio, stretch }].
  -- מה שנשמר הוא בדיוק מה שה-API כבר מחזיר, כדי שהקריאה לא תצטרך מתאם.
  add column if not exists candidates jsonb,
  -- מזהה ההרצה שממנה באה הגרסה (`runId`). מקשר בין גרסה שנבחרה לבין ההרצה
  -- שהציעה אותה, גם אחרי שהגרסה נשמרה בנפרד.
  add column if not exists generation_id uuid,
  -- איזו הצעה נבחרה מתוך `candidates` של ההרצה. null = הגרסה לא נוצרה מבחירה.
  -- בלי זה אפשר לדעת *מה* הוזמן (ההזמנה מצביעה על גרסה) אבל לא *איזו מהחלופות*
  -- זו הייתה — השוואת SVG לא עוזרת, כי הגרסה נשמרת בצורתה הקנונית ולא כמחרוזת
  -- שההצעה נשאה. זה בדיוק מה שנשבר פעם אחת וגרם לכך שאף הצעה לא סומנה כמוצגת.
  add column if not exists picked_index int;

comment on column design_versions.candidates is
  'ההצעות שהוצעו יחד עם הגרסה. נספח לגרסה, לא ישויות עצמאיות.';
comment on column design_versions.generation_id is
  'runId של ההרצה שהציעה את הגרסה.';
comment on column design_versions.picked_index is
  'האינדקס שנבחר מתוך ההצעות. null = לא נוצרה מבחירה.';
