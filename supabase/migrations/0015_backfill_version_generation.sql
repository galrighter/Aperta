-- קישור אחורה של גרסאות להרצה שיצרה אותן.
--
-- `design_versions.generation_id` נוסף ב-0012, וכל גרסה שנשמרה לפניו לא נושאת
-- אותו. מסלול "קובץ מוכן לחיתוך" (`/api/vectorize`) גם לא מסר אותו כלל, גם
-- אחרי 0012. התוצאה זהה בשני המקרים: שורת יומן שלא יודעת על שום גרסה — בלי
-- מספר גרסה, בלי הגישור שנוסף אחרי המעקב, ובלי הקובץ לייצור. העיצוב עצמו
-- שלם; מה שחסר הוא החוט בין ההרצה לתוצאה שלה.
--
-- ההתאמה: ההרצה **האחרונה שקדמה** לגרסה, באותו עיצוב, בטווח של 30 דקות.
-- הגרסה נכתבת בסוף הצינור — שניות עד דקות אחרי ששורת ההרצה נרשמה — ולכן
-- ההרצה הקרובה שלפניה היא זו שייצרה אותה. שתי הגבלות במכוון:
--
--   · **חלון ולא התאמה חופשית.** גרסה שנשמרה יום אחרי ההרצה האחרונה של אותו
--     עיצוב אינה תוצאה שלה. שורה בלי קישור עדיפה על קישור שקרי: היומן מציג
--     "אין גרסה", וזה נכון, במקום להציע קובץ חיתוך של הרצה אחרת.
--   · **רק שורות ריקות.** `where generation_id is null` — הקישור שנכתב בזמן
--     אמת מדויק, וניחוש לא דורס אותו. זה גם מה שהופך את הקובץ לאידמפוטנטי,
--     וזה הכרחי כאן: migrate.yml מריץ את *כל* קובצי המיגרציה בכל דחיפה.
--
-- `picked_index` נשאר null בשורות האלה, ולכן `versionRole` ממשיך לראות בהן
-- "plain" ולא "pick" — הקישור משנה את היומן ואת קבצי הייצור, ולא את מסע
-- הלקוחה.

update design_versions v
set generation_id = m.run_id
from (
  select
    v2.id as version_id,
    (
      select r.id
      from generation_runs r
      where r.design_id = v2.design_id
        and r.created_at <= v2.created_at
        and v2.created_at - r.created_at < interval '30 minutes'
      order by r.created_at desc
      limit 1
    ) as run_id
  from design_versions v2
  where v2.generation_id is null
) m
where v.id = m.version_id
  and m.run_id is not null;
