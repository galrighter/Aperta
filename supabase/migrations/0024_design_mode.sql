-- המסלול שהעיצוב נוצר בו — `story`, או ריק לכל השאר.
--
-- **למה זה חייב לשבת במסד ולא בדפדפן.** במסלול Story סדר השלבים שונה: המידה
-- נשאלת **אחרי** התוצאה ולא לפניה (`STORY_RAIL`), והאורך שברשומה עד אז הוא עוגן
-- תכנוני ולא מדידה. הדגל שהחזיק את הידיעה הזו (`CreateState.story`) חי בזיכרון
-- העמוד בלבד, ולכן חזרה לעיצוב שמור אתחלה אותו ל-false: מסך המידות ירד מהסרגל,
-- "בחר עיצוב" דילג ממסך התוצאה ישר לסיכום, וההזמנה יצאה עם עוגן ברירת המחדל —
-- בלי שאיש נשאל ובלי שום חיווי. זה בדיוק הכשל ש-AP-0065 אוסר.
--
-- **ולמה לא ב-localStorage.** שם כבר יושב מה שהדפדפן זוכר על העיצוב (`fit`,
-- הבריף), אבל שני המסלולים שבהם לקוחה חוזרת לעיצוב שלה אינם בהכרח אותו מכשיר:
-- הקישור מהמייל ("העיצוב שלך מוכן") ו-`?resume=` נפתחים גם בטלפון אחר. המסלול
-- שבו נוצר העיצוב הוא עובדה עליו, לא העדפת תצוגה — ולכן הוא נשמר עליו.
--
-- העמודה nullable ובלי ברירת מחדל: כל מה שנוצר עד היום נשאר כפי שהוא, וכל קורא
-- שאינו מכיר אותה ממשיך לעבוד. `isStory` (lib/story/mode.ts) הוא הבודק היחיד.

alter table designs add column if not exists mode text;

do $$
begin
  alter table designs add constraint designs_mode_check
    check (mode is null or mode in ('story'));
exception
  when duplicate_object then null;
end $$;

