-- לסיים**: התיאור שנשלח למודל, החלוקה לחלופות, המידות שהוזמנו והגשרים שנחתכו
-- בכיתוב חיו רק בזיכרון של הבקשה שפתחה את ההרצה. נהרגה הבקשה — נהרג הידע, וגם
-- כשהתוצאה יושבת בקופסה אין מי שידע מה לעשות איתה. זה מה שהשאיר הרצות תקועות
-- על 'running' עד שהוכרזו כתקועות (AP-0090, docs/C2_RESILIENT_GENERATION.md §5).
